class Translator:
    """Looks up UI strings for the current language."""

    def __init__(self, language: str = config.LANGUAGE) -> None:
        self.language = language

    def lookup(self, key: str) -> str | None:
        """Return the string for ``key`` or None if no language defines it."""
        table = STRINGS.get(self.language, {})
        return table.get(key) or STRINGS[config.LANGUAGE_EN].get(key)

    def __call__(self, key: str, **values: object) -> str:
        """Return the translated string for ``key``, formatted with ``values``."""
        table = STRINGS.get(self.language, {})
        template = table.get(key) or STRINGS[config.LANGUAGE_EN].get(key, key)
        return template.format(**values) if values else template
